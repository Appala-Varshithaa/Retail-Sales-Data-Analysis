import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
df=pd.read_csv('sales_data_5000.csv')

df.head()

df.info()

df.describe()

df.isnull().sum()

df=df.dropna()

df.isnull().sum()

df=df.copy()

df["Order_Date"]=pd.to_datetime(df["Order_Date"])

df.info()

df["Month"]=df["Order_Date"].dt.month_name()

df["Year"]=df["Order_Date"].dt.year

df.info()

#Revenue col
df["Revenue"]=df["Quantity"]*df["Price"]

#1️⃣ Total Revenue
Total_Revenue =df["Revenue"].sum()
print(Total_Revenue)

#2️⃣ Top-Selling Products
top_products=df.groupby("Product")["Quantity"].sum().sort_values(ascending=False).head(10)
print(top_products)

#3️⃣ Revenue by Region
region_sales=df.groupby("Region")["Revenue"].sum().sort_values(ascending=False)
print(region_sales)

#4️⃣ Revenue by Category
Revenue_cat=df.groupby("Category")["Revenue"].sum().sort_values(ascending=False)
print(Revenue_cat)

#5️⃣ Monthly Revenue
Monthly_Revenue=df.groupby("Month")["Revenue"].sum().sort_values(ascending=True)
print(Monthly_Revenue)

#Visualizations
#Chart 1: Top 10 Products
Top_products=df.groupby("Product")["Quantity"].sum().sort_values(ascending=False).head(10)
print(Top_products)

plt.figure(figsize=(9, 6))
plt.bar(Top_products.index,Top_products.values,color="pink",edgecolor="black")
plt.title("Top 10 Products")
plt.xlabel("products")
plt.ylabel("Quantity Sold")
plt.xticks(rotation=45)
plt.show()

#Total Revenue for each region
Total_Revenue=df.groupby("Region")["Revenue"].sum().sort_values(ascending=False)
print(Total_Revenue)

#Revenue by Region
plt.figure(figsize=(9,5))
plt.bar(Total_Revenue.index,Total_Revenue.values)
plt.title("Revenue by Region")
plt.xlabel("Region")
plt.ylabel("Revenue")
plt.show()

#Revenue by Category
Total_Rev=df.groupby("Category")["Revenue"].sum().sort_values(ascending=False)
print(Total_Rev)

plt.figure(figsize=(9,5))
plt.plot(Total_Rev.index,Total_Rev.values)
plt.title("Revenue by Category")
plt.xlabel("Category")
plt.ylabel("Revenue")
plt.show()

#Distribution of Order Revenue
plt.figure(figsize=(9,6))
sns.histplot(df["Revenue"],bins=30,kde=True)
plt.title("Distribution of Order Revenue")
plt.xlabel("Revenue per Order")
plt.ylabel("Number of Orders")
plt.show()

#Revenue Distribution & Outliers
plt.figure(figsize=(10,8))
sns.boxplot(df["Revenue"])
plt.title("Revenue Distribution & Outliers")
plt.xlabel("Revenue per Order")
plt.show()